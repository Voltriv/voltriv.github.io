#!/usr/bin/env node
/**
 * Builds src/data/localMediaManifest.ts from the files inside public/pics and vid.
 * This lets the gallery automatically pick up new local assets without manually editing TS files.
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, "..");

const MEDIA_DIR = path.join(projectRoot, "public", "pics and vid");
const OUTPUT_FILE = path.join(projectRoot, "src", "data", "localMediaManifest.ts");
const METADATA_FILE = path.join(__dirname, "media-metadata.json");

const IMAGE_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".gif", ".webp", ".avif"]);
const VIDEO_EXTENSIONS = new Set([".mp4", ".webm", ".mov", ".m4v"]);

async function loadMetadata() {
  try {
    const raw = await fs.readFile(METADATA_FILE, "utf8");
    return JSON.parse(raw);
  } catch (error) {
    if (error.code === "ENOENT") {
      return {};
    }
    throw error;
  }
}

function createEntry({ fileName, meta, isVideo }) {
  const baseMeta = meta ?? {};
  if (baseMeta.skip) {
    return null;
  }

  return {
    fileName,
    alt: baseMeta.alt ?? "",
    category: baseMeta.category ?? (isVideo ? "video" : "favorites"),
    caption: baseMeta.caption ?? "",
    credit: baseMeta.credit ?? "",
    isVideo: baseMeta.isVideo ?? (isVideo ? true : undefined),
  };
}

async function generate() {
  const [metadata, items] = await Promise.all([loadMetadata(), fs.readdir(MEDIA_DIR)]);

  const entries = items
    .map((fileName) => {
      const ext = path.extname(fileName).toLowerCase();
      const isVideo = VIDEO_EXTENSIONS.has(ext);
      const isImage = IMAGE_EXTENSIONS.has(ext);
      if (!isVideo && !isImage) {
        return null;
      }
      return createEntry({
        fileName,
        meta: metadata[fileName],
        isVideo,
      });
    })
    .filter(Boolean)
    .sort((a, b) => a.fileName.localeCompare(b.fileName, undefined, { numeric: true, sensitivity: "base" }));

  const lines = entries.map((entry) => {
    const props = [
      `    id: ${JSON.stringify(entry.fileName)},`,
      `    src: mediaAsset(${JSON.stringify(entry.fileName)}),`,
      `    alt: ${JSON.stringify(entry.alt)},`,
      `    category: ${JSON.stringify(entry.category)},`,
      `    caption: ${JSON.stringify(entry.caption)},`,
      `    credit: ${JSON.stringify(entry.credit)},`,
    ];
    if (entry.isVideo) {
      props.push(`    isVideo: true,`);
    }
    return `  {\n${props.join("\n")}\n  }`;
  });

  const fileContents = `// This file is auto-generated by scripts/generate-media-manifest.mjs\n` +
    `// Run "npm run generate-media" to refresh it after adding/removing assets.\n` +
    `import { mediaAsset } from "@/lib/constants";\n` +
    `import type { GalleryItem } from "@/features/story/sections/galleryTypes";\n\n` +
    `export const LOCAL_MEDIA: GalleryItem[] = [\n${lines.join(",\n")}\n];\n`;

  await fs.mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
  await fs.writeFile(OUTPUT_FILE, fileContents, "utf8");
}

generate().catch((error) => {
  console.error("[generate-media-manifest] Failed:", error);
  process.exitCode = 1;
});
